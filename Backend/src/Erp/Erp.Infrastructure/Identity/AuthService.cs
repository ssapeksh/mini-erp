using Erp.Core.Common;
using Erp.Core.Dtos;
using Erp.Core.Entities;
using Erp.Infrastructure.Persistence;
using Microsoft.AspNetCore.Identity;
using Microsoft.EntityFrameworkCore;
using Microsoft.Extensions.Logging;
using Microsoft.Extensions.Options;

namespace Erp.Infrastructure.Identity;

/// <summary>
/// Login, refresh-token rotation, logout and single-session enforcement.
///
/// JWT flow:
///   1. POST /auth/login with credentials
///   2. verify the password hash -> end any other active session (single session)
///      -> create a session -> issue a 15-min access token (claims: user, role,
///      permissions, session id) + a 7-day refresh token (only its hash is stored)
///   3. client sends "Authorization: Bearer &lt;access token&gt;" on every call
///   4. when it expires: POST /auth/refresh -> the old refresh token is revoked
///      and a new pair is issued (ROTATION)
///   5. a refresh token used twice means it was stolen -> revoke the whole session
/// </summary>
public sealed class AuthService(
    ErpDbContext db,
    JwtTokenService tokens,
    IPasswordHasher<User> hasher,
    IOptions<JwtSettings> jwtOptions,
    TimeProvider clock,
    ILogger<AuthService> logger)
{
    private const string InvalidCredentials = "Invalid user name or password.";   // same message for both cases: don't reveal which was wrong

    public async Task<AuthResponse> LoginAsync(LoginRequest request, ClientInfo client, CancellationToken ct = default)
    {
        var (user, result) = await CheckPasswordAsync(request, client, ct);

        DateTime now = Now;
        await using var tx = await db.Database.BeginTransactionAsync(ct);

        if (result == PasswordVerificationResult.SuccessRehashNeeded)
            user.PasswordHash = hasher.HashPassword(user, request.Password);   // upgrade old hash formats transparently
        user.LastLoginOn = now;

        // SINGLE SESSION: a new login ends the previous one (the filtered unique index
        // UX_UserSessions_OneActivePerUser would reject a second active row anyway).
        // ExecuteUpdateAsync = one set-based UPDATE statement, no entities loaded.
        int ended = await db.UserSessions
            .Where(s => s.UserId == user.Id && s.EndedOn == null)
            .ExecuteUpdateAsync(s => s.SetProperty(x => x.EndedOn, now)
                                      .SetProperty(x => x.EndReason, SessionEndReasons.NewLogin), ct);
        await db.RefreshTokens
            .Where(t => t.UserId == user.Id && t.RevokedOn == null)
            .ExecuteUpdateAsync(s => s.SetProperty(x => x.RevokedOn, now), ct);
        if (ended > 0)
            logger.LogInformation("User {UserName} logged in again; {Count} previous session(s) ended", user.UserName, ended);

        var session = new UserSession
        {
            UserId = user.Id,
            IpAddress = Truncate(client.IpAddress, 45),
            UserAgent = Truncate(client.UserAgent, 300),
            StartedOn = now,
            LastActivityOn = now
        };
        db.UserSessions.Add(session);
        await db.SaveChangesAsync(ct);                       // session.Id generated by NEWSEQUENTIALID()

        var response = await IssueTokensAsync(user, session.Id, now, ct);
        await tx.CommitAsync(ct);

        logger.LogInformation("User {UserName} logged in, session {SessionId}", user.UserName, session.Id);
        return response;
    }

    /// <summary>Password check only, no session or tokens (used by the legacy cookie login).</summary>
    public async Task<UserInfoDto> VerifyCredentialsAsync(LoginRequest request, ClientInfo client, CancellationToken ct = default)
    {
        var (user, _) = await CheckPasswordAsync(request, client, ct);
        return ToUserInfo(user);
    }

    private async Task<(User User, PasswordVerificationResult Result)> CheckPasswordAsync(
        LoginRequest request, ClientInfo client, CancellationToken ct)
    {
        var user = await LoadUserWithPermissionsAsync(u => u.UserName == request.UserName, ct);
        if (user is null || !user.IsActive)
        {
            // logging failed logins (with IP) is part of securing an API
            logger.LogWarning("Failed login for unknown/inactive user {UserName} from {Ip}", request.UserName, client.IpAddress);
            throw new AuthenticationFailedException(InvalidCredentials);
        }

        var result = hasher.VerifyHashedPassword(user, user.PasswordHash, request.Password);
        if (result == PasswordVerificationResult.Failed)
        {
            logger.LogWarning("Failed login (bad password) for {UserName} from {Ip}", request.UserName, client.IpAddress);
            throw new AuthenticationFailedException(InvalidCredentials);
        }
        return (user, result);       // tuple return
    }

    public async Task<AuthResponse> RefreshAsync(string refreshToken, CancellationToken ct = default)
    {
        DateTime now = Now;
        string hash = JwtTokenService.Hash(refreshToken);
        var stored = await db.RefreshTokens.FirstOrDefaultAsync(t => t.TokenHash == hash, ct)
                     ?? throw new AuthenticationFailedException("Invalid refresh token.");

        if (stored.RevokedOn is not null)
        {
            // REUSE DETECTION: a rotated (already used) token came back. Either the
            // client is buggy or the token was stolen. Kill the whole session.
            logger.LogWarning("Refresh token reuse detected for user {UserId}, session {SessionId}", stored.UserId, stored.SessionId);
            if (stored.SessionId is { } sid) await EndSessionAsync(sid, SessionEndReasons.Revoked, ct);
            throw new AuthenticationFailedException("Refresh token was already used. Please log in again.");
        }
        if (stored.ExpiresOn <= now)
            throw new AuthenticationFailedException("Refresh token expired. Please log in again.");

        var session = stored.SessionId is { } sessionId
            ? await db.UserSessions.FirstOrDefaultAsync(s => s.Id == sessionId, ct)
            : null;
        if (session is not { IsActive: true })
            throw new AuthenticationFailedException("Your session has ended. Please log in again.");

        // Reload the user: permissions may have changed since login
        var user = await LoadUserWithPermissionsAsync(u => u.Id == stored.UserId, ct);
        if (user is not { IsActive: true })
            throw new AuthenticationFailedException("User is no longer active.");

        await using var tx = await db.Database.BeginTransactionAsync(ct);
        session.LastActivityOn = now;
        var response = await IssueTokensAsync(user, session.Id, now, ct, rotate: stored);
        await tx.CommitAsync(ct);
        return response;
    }

    public async Task LogoutAsync(Guid sessionId, CancellationToken ct = default) =>
        await EndSessionAsync(sessionId, SessionEndReasons.Logout, ct);

    /// <summary>Ends a session and revokes its refresh tokens. Idempotent.</summary>
    public async Task<bool> EndSessionAsync(Guid sessionId, string reason, CancellationToken ct = default)
    {
        DateTime now = Now;
        int ended = await db.UserSessions
            .Where(s => s.Id == sessionId && s.EndedOn == null)
            .ExecuteUpdateAsync(s => s.SetProperty(x => x.EndedOn, now).SetProperty(x => x.EndReason, reason), ct);
        await db.RefreshTokens
            .Where(t => t.SessionId == sessionId && t.RevokedOn == null)
            .ExecuteUpdateAsync(s => s.SetProperty(x => x.RevokedOn, now), ct);
        return ended > 0;
    }

    public async Task<UserInfoDto> GetUserInfoAsync(int userId, CancellationToken ct = default)
    {
        var user = await LoadUserWithPermissionsAsync(u => u.Id == userId, ct) ?? throw NotFoundException.For("User", userId);
        return ToUserInfo(user);
    }

    public async Task<IReadOnlyList<SessionDto>> GetSessionsAsync(bool activeOnly, CancellationToken ct = default) =>
        await db.UserSessions.AsNoTracking()
            .Where(s => !activeOnly || s.EndedOn == null)
            .OrderByDescending(s => s.LastActivityOn)
            .Take(200)
            .Select(s => new SessionDto(s.Id, s.UserId, s.User.UserName, s.User.FullName, s.IpAddress, s.UserAgent,
                                        s.StartedOn, s.LastActivityOn, s.EndedOn, s.EndReason))
            .ToListAsync(ct);

    private async Task<AuthResponse> IssueTokensAsync(User user, Guid sessionId, DateTime now, CancellationToken ct,
                                                      RefreshToken? rotate = null)
    {
        var permissions = user.Role.RolePermissions.Select(rp => rp.Permission.Code).OrderBy(c => c).ToList();
        var (accessToken, accessExpires) = tokens.CreateAccessToken(user, user.Role.Name, permissions, sessionId);

        string refreshToken = JwtTokenService.GenerateRefreshToken();
        string refreshHash = JwtTokenService.Hash(refreshToken);
        DateTime refreshExpires = now.AddDays(jwtOptions.Value.RefreshTokenDays);

        if (rotate is not null)
        {
            rotate.RevokedOn = now;
            rotate.ReplacedByTokenHash = refreshHash;           // keeps the rotation chain for auditing
        }
        db.RefreshTokens.Add(new RefreshToken
        {
            UserId = user.Id, SessionId = sessionId, TokenHash = refreshHash, ExpiresOn = refreshExpires, CreatedOn = now
        });
        await db.SaveChangesAsync(ct);

        return new AuthResponse(accessToken, accessExpires, refreshToken, refreshExpires, sessionId, ToUserInfo(user, permissions));
    }

    private Task<User?> LoadUserWithPermissionsAsync(System.Linq.Expressions.Expression<Func<User, bool>> predicate, CancellationToken ct) =>
        db.Users
            .Include(u => u.Role).ThenInclude(r => r.RolePermissions).ThenInclude(rp => rp.Permission)
            .AsSplitQuery()
            .FirstOrDefaultAsync(predicate, ct);

    private static UserInfoDto ToUserInfo(User user, IReadOnlyList<string>? permissions = null) =>
        new(user.Id, user.UserName, user.FullName, user.Role.Name,
            permissions ?? user.Role.RolePermissions.Select(rp => rp.Permission.Code).OrderBy(c => c).ToList());

    private DateTime Now => clock.GetUtcNow().UtcDateTime;

    private static string? Truncate(string? value, int max) => value is null || value.Length <= max ? value : value[..max];
}
